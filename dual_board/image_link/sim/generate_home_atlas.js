// Deterministic RTL asset generation from the ModelSim capture of the unchanged
// single-board renderer. No resampling, palette quantisation or image editing.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.resolve(__dirname, '..');
const dst = path.join(root, 'rtl', 'home_assets');
fs.mkdirSync(dst, {recursive: true});
const input = fs.readFileSync(path.join(__dirname, 'home_reference_runs.csv'), 'utf8');
const colors = ['010203']; // index 0 means preserve the photograph
const colorIds = new Map([[colors[0], 0]]);
const rows = Array.from({length: 1024}, () => []);
for (const line of input.trim().split(/\r?\n/)) {
    const [p, y, count, rawColor] = line.split(',');
    const color = rawColor.toLowerCase();
    if (!colorIds.has(color)) {colorIds.set(color, colors.length); colors.push(color);}
    if (colors.length > 256) throw Error('UI palette overflow');
    let n = Number(count);
    while (n) {
        const length = Math.min(n, 256);
        rows[Number(p)*512+Number(y)].push(((length-1)<<8)|colorIds.get(color));
        n -= length;
    }
}
const words = [], offsets = [], dictionary = new Map();
for (let i=0; i<1024; i++) {
    const row = rows[i].length ? rows[i] : [0xff00,0xff00,0x7f00];
    if (row.reduce((n,w)=>n+(w>>8)+1,0)!==640) throw Error('Invalid row '+i);
    const key = row.join(',');
    if (!dictionary.has(key)) {dictionary.set(key,words.length); words.push(...row);}
    offsets.push(dictionary.get(key));
}
const banks = Math.ceil(words.length/2048);
if (banks > 7) throw Error('Unexpected atlas growth; review B BRAM32K budget');
let rtl = '// GENERATED by sim/generate_home_atlas.js; source is the existing UI.\n';
rtl += 'module home_run_rom(input wire clk,enable,input wire [13:0] address,output reg [15:0] data);\n';
rtl += `wire [15:0] q[0:${banks-1}];reg [2:0] bank;always @(posedge clk) if(enable) bank<=address[13:11];\n`;
rtl += 'always @* begin case(bank)\n';
for(let b=0;b<banks;b++) rtl+=`3'd${b}:data=q[${b}];\n`;
rtl += 'default:data=16\'h0000;endcase end\n';
for(let b=0;b<banks;b++) {
    rtl += 'EG_PHY_BRAM32K #(.MODE("DP16K"),.DATA_WIDTH_A("16"),.DATA_WIDTH_B("16"),.REGMODE_A("NOREG"),\n';
    for(let block=0;block<128;block++) {
        const chunk = Array.from({length:16},(_,j)=>words[b*2048+block*16+j]||0).reverse();
        rtl += `.INIT_${block.toString(16).toUpperCase().padStart(2,'0')}(256'h${chunk.map(w=>w.toString(16).padStart(4,'0')).join('')})${block===127?')':','}\n`;
    }
    rtl += `ram${b}(.doa(q[${b}]),.dia(16'd0),.addra(address[10:0]),.bytea(1'b0),.bytewea(1'b0),\n`;
    rtl += `.csa(enable && address[13:11]==3'd${b}),.wea(1'b0),.clka(clk),.rsta(1'b0),.ocea(1'b1),\n`;
    rtl += '.dob(),.dib(16\'d0),.addrb(11\'d0),.byteb(1\'b0),.byteweb(1\'b0),.csb(1\'b0),.web(1\'b0),.clkb(clk),.rstb(1\'b0),.oceb(1\'b1));\n';
}
rtl += 'endmodule\n\nmodule home_row_rom(input wire clk,enable,input wire [9:0] address,output reg [13:0] data);\n';
rtl += 'reg [13:0] mem[0:1023]; /* fehdl force_ram=1, ram_style="bram" */\ninitial begin\n';
offsets.forEach((v,i)=>{rtl+=`mem[${i}]=14'd${v};\n`;});
rtl += 'end\nalways @(posedge clk) if(enable) data<=mem[address];\nendmodule\n';
fs.writeFileSync(path.join(dst,'home_atlas_rom.v'),rtl);
let palette = '// GENERATED lossless palette. Index 0 is transparent, never a visible colour.\n';
palette += 'module home_palette_rom(input wire clk,enable,input wire [7:0] index,output reg [23:0] rgb);\n';
palette += 'reg [23:0] mem[0:255]; /* fehdl force_ram=1, ram_style="bram" */\ninitial begin\n';
for(let i=0;i<256;i++) palette+=`mem[${i}]=24'h${colors[i]||'000000'};\n`;
palette += 'end\nalways @(posedge clk) if(enable) rgb<=mem[index];\nendmodule\n';
fs.writeFileSync(path.join(dst,'home_palette_rom.v'),palette);
const ref = [];
for(let p=0;p<2;p++) for(let y=0;y<480;y++) for(const w of rows[p*512+y])
    for(let x=0;x<(w>>8)+1;x++) ref.push((w&255).toString(16).padStart(2,'0'));
fs.writeFileSync(path.join(__dirname,'home_reference_indices.hex'),ref.join('\n')+'\n');
const summary = {sourceSha256:crypto.createHash('sha256').update(input).digest('hex'),
    pages:2,width:640,height:480,colors:colors.length,uniqueRows:dictionary.size,
    runWords:words.length,runBram32K:banks,rowBits:1024*14,lossless:true};
fs.writeFileSync(path.join(dst,'home_atlas_manifest.json'),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify(summary,null,2));
