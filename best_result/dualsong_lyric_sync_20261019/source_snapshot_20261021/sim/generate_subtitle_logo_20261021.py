"""20261021 assets: B dashboard subtitle glyphs and the A home-page logo badge.

B: 16 glyphs 32x32 (Noto Sans SC Medium) for the scrolling line and 4 glyphs
   64x64 (Noto Sans SC Bold) for the hazard text, 2-bit coverage, each set in
   one EG_PHY_BRAM32K (DP16K, 16-bit words = 8 pixels, pixel k in bits 2k+1:2k).
A: the logo of 00_0.bmp cropped from its white page, 68x44, 8-colour palette,
   3 pixels per 9-bit word (pixel k in bits 3k+2:3k), 23 words per row.

Run with the Python 3.7 + PIL interpreter.  Writes RTL + previews.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent          # dual_board/image_link
RTL = ROOT / 'rtl' / 'subtitle_20261021'
OUT = ROOT / 'sim' / 'subtitle_20261021'
RTL.mkdir(parents=True, exist_ok=True)
OUT.mkdir(parents=True, exist_ok=True)
FONTS = Path('C:/Windows/Fonts')
MEDIUM = FONTS / 'Noto Sans SC Medium (TrueType).otf'
BOLD = FONTS / 'Noto Sans SC Bold (TrueType).otf'
LOGO_SRC = Path('C:/Users/28492/Desktop/车载图片/00_0.bmp')
DASH_BMP = ROOT.parent.parent / 'best_result/dualsong_song6_20261014/TF_CARD_CLEAN_20261017/IMAGE1.BMP'

TICKER = '安路科技提醒您行车安全，祝您旅途愉快'
WARN = '注意安全'
SS = 8                                                # supersampling factor
# Coverage -> 2-bit level.  Thresholds keep stems solid and edges soft.
LEVELS = (0.16, 0.45, 0.78)


def quant(c):
    return sum(c >= t for t in LEVELS)


def glyph(ch, font_path, cell, size, dy=0):
    """Return cell*cell list of 2-bit levels for ch, centred in the cell."""
    big = cell * SS
    font = ImageFont.truetype(str(font_path), size * SS)
    im = Image.new('L', (big, big), 0)
    d = ImageDraw.Draw(im)
    x0, y0, x1, y1 = d.textbbox((0, 0), ch, font=font)
    # Horizontal: ink-centred.  Vertical: centred on the em box of '国' so
    # every glyph (including the comma) shares one baseline.
    gx0, gy0, gx1, gy1 = d.textbbox((0, 0), '国', font=font)
    ox = (big - (x1 - x0)) // 2 - x0
    oy = (big - (gy1 - gy0)) // 2 - gy0 + dy * SS
    d.text((ox, oy), ch, font=font, fill=255)
    small = im.resize((cell, cell), Image.BOX)
    return [quant(v / 255.0) for v in small.getdata()]


def bram32k(name, words, comment):
    assert len(words) <= 2048
    words = words + [0] * (2048 - len(words))
    v = ['// ' + comment,
         'module %s(input wire clk,ce,input wire [10:0] addr,output wire [15:0] q);' % name,
         'EG_PHY_BRAM32K #(.MODE("DP16K"),.DATA_WIDTH_A("16"),.DATA_WIDTH_B("16"),',
         '.REGMODE_A("NOREG"),.REGMODE_B("NOREG"),']
    for i in range(128):
        val = sum(w << (16 * j) for j, w in enumerate(words[i * 16:i * 16 + 16]))
        v.append(".INIT_%02X(256'h%064X)%s" % (i, val, ',' if i < 127 else ')'))
    v += ["u_ram(.doa(q),.dia(16'd0),.addra(addr),.bytea(1'b0),.bytewea(1'b0),",
          ".csa(ce),.wea(1'b0),.clka(clk),.rsta(1'b0),.ocea(1'b1),",
          ".dob(),.dib(16'd0),.addrb(11'd0),.byteb(1'b0),.byteweb(1'b0),",
          ".csb(1'b0),.web(1'b0),.clkb(1'b0),.rstb(1'b0),.oceb(1'b0));",
          'endmodule', '']
    return '\n'.join(v)


def pack8(pixels):
    return [sum(pixels[w * 8 + k] << (2 * k) for k in range(8)) for w in range(len(pixels) // 8)]


# ---------------- B ticker / warning glyph ROMs ----------------
uniq = []
for ch in TICKER:
    if ch not in uniq:
        uniq.append(ch)
assert len(uniq) <= 16, uniq
ticker_glyphs = [glyph(ch, MEDIUM, 32, 27, dy=0) for ch in uniq]
ticker_px = sum(ticker_glyphs, []) + [0] * (32 * 32 * (16 - len(uniq)))
warn_glyphs = [glyph(ch, BOLD, 64, 56, dy=0) for ch in WARN]
warn_px = sum(warn_glyphs, [])
seq = [uniq.index(ch) for ch in TICKER]

seq_case = '\n'.join("    5'd%d: glyph=4'd%d;" % (i, g) for i, g in enumerate(seq))
rom_v = bram32k('subtitle_ticker_rom', pack8(ticker_px),
                'Generated by sim/generate_subtitle_logo_20261021.py: %d glyphs 32x32 '
                '(Noto Sans SC Medium), 2-bit coverage: %s' % (len(uniq), ''.join(uniq)))
rom_v += bram32k('subtitle_warning_rom', pack8(warn_px),
                 'Generated: 4 glyphs 64x64 (Noto Sans SC Bold), 2-bit coverage: ' + WARN)
rom_v += '\n'.join([
    '// Character position (32 px advance) -> glyph slot for: ' + TICKER,
    'module subtitle_ticker_text(input wire [4:0] pos,output reg [3:0] glyph,output wire valid);',
    "assign valid=pos<5'd%d;" % len(TICKER),
    'always @* begin',
    '    case(pos)',
    seq_case,
    "    default: glyph=4'd0;",
    '    endcase',
    'end',
    'endmodule', ''])
(RTL / 'subtitle_glyph_rom.v').write_bytes(rom_v.encode('utf-8'))
(OUT / 'ticker_px.hex').write_text('\n'.join('%x' % p for p in ticker_px) + '\n')
(OUT / 'warn_px.hex').write_text('\n'.join('%x' % p for p in warn_px) + '\n')
(OUT / 'ticker_seq.txt').write_text(' '.join(map(str, seq)) + '\n')

# ---------------- A logo badge ROM ----------------
LW, LH = 68, 44
src = Image.open(str(LOGO_SRC)).convert('RGB')
px = src.load()
ink = [(x, y) for y in range(src.height) for x in range(src.width) if sum(px[x, y]) < 690]
bx0 = min(x for x, _ in ink); bx1 = max(x for x, _ in ink)
by0 = min(y for _, y in ink); by1 = max(y for _, y in ink)
crop = src.crop((bx0, by0, bx1 + 1, by1 + 1))
# Fit inside 68x44 keeping the aspect ratio, on the badge white.
PLATE = (250, 251, 253)
scale = min(LW / crop.width, LH / crop.height)
sw, sh = max(1, round(crop.width * scale)), max(1, round(crop.height * scale))
logo = Image.new('RGB', (LW, LH), PLATE)
logo.paste(crop.resize((sw, sh), Image.LANCZOS), ((LW - sw) // 2, (LH - sh) // 2))
NAVY = (28, 45, 78)
RED = (237, 28, 36)


def mix(a, b, t):
    return tuple(round(a[i] * (1 - t) + b[i] * t) for i in range(3))


palette = [PLATE, NAVY, mix(PLATE, NAVY, 0.70), mix(PLATE, NAVY, 0.40), mix(PLATE, NAVY, 0.15),
           RED, mix(PLATE, RED, 0.60), mix(PLATE, RED, 0.28)]


def nearest(c):
    return min(range(8), key=lambda i: sum((c[k] - palette[i][k]) ** 2 for k in range(3)))


lp = logo.load()
idx = [nearest(lp[x, y]) for y in range(LH) for x in range(LW)]
err = sum(sum(abs(lp[x, y][k] - palette[idx[y * LW + x]][k]) for k in range(3))
          for y in range(LH) for x in range(LW)) / (LW * LH * 3)
WPR = 23                                              # 9-bit words per row
words = []
for y in range(LH):
    row = idx[y * LW:(y + 1) * LW] + [0] * (WPR * 3 - LW)
    words += [row[3 * w] | (row[3 * w + 1] << 3) | (row[3 * w + 2] << 6) for w in range(WPR)]
logo_v = ['// Generated by sim/generate_subtitle_logo_20261021.py from 00_0.bmp (logo only,',
          '// white page cropped): %dx%d, 8-colour palette, mean |err| %.1f/255.' % (LW, LH, err),
          '// 3 pixels per 9-bit word, %d words per row: one BRAM9K.' % WPR,
          'module home_logo_rom(input wire clk,ce,input wire [9:0] addr,output reg [8:0] q);',
          'reg [8:0] rom[0:1023]; /* fehdl force_ram=1, ram_style="bram" */',
          'integer i;',
          'initial begin',
          "    for(i=0;i<1024;i=i+1) rom[i]=9'd0;"]
logo_v += ["    rom[%d]=9'h%03x;" % (i, w) for i, w in enumerate(words) if w]
logo_v += ['end', 'always @(posedge clk) if(ce) q<=rom[addr];', 'endmodule', '',
           'module home_logo_palette(input wire [2:0] index,output reg [23:0] rgb);',
           'always @* begin', '    case(index)']
logo_v += ["    3'd%d: rgb=24'h%02X%02X%02X;" % ((i,) + c) for i, c in enumerate(palette)]
logo_v += ['    endcase', 'end', 'endmodule', '']
(RTL / 'home_logo_rom.v').write_bytes('\n'.join(logo_v).encode('utf-8'))
(OUT / 'logo_idx.hex').write_text('\n'.join('%x' % i for i in idx) + '\n')
(OUT / 'logo_palette.hex').write_text('\n'.join('%02x%02x%02x' % c for c in palette) + '\n')

# ---------------- previews ----------------
dec = Image.new('RGB', (LW, LH))
dec.putdata([palette[i] for i in idx])
dec.resize((LW * 6, LH * 6), Image.NEAREST).save(str(OUT / 'logo_rom_preview.png'))


def strip(glyphs, cell, order):
    im = Image.new('L', (cell * len(order), cell))
    for n, g in enumerate(order):
        im.paste(Image.frombytes('L', (cell, cell), bytes(v * 85 for v in glyphs[g])), (n * cell, 0))
    return im


strip(ticker_glyphs, 32, seq).save(str(OUT / 'ticker_strip.png'))
strip(warn_glyphs, 64, range(4)).save(str(OUT / 'warn_strip.png'))
print('ticker glyphs', ''.join(uniq), 'seq', seq)
print('logo bbox', (bx0, by0, bx1, by1), 'scaled', (sw, sh), 'palette err %.2f' % err,
      'words', len(words))

# ---------------- B colour ROM (20261021 rev 2) ----------------
# Address {kind[1:0], sel[4:0], w-1[2:0]}: kind 0 ticker (sel=row, white ->
# sky-blue), 1 hazard text (sel=breath 0..31), 2 rule, 3 hazard bar.  w is the
# opacity in eighths, mixed over the band's measured mean artwork colour.
dash = Image.open(str(DASH_BMP)).convert('RGB')
dp = dash.load()
band = [dp[x, y] for y in range(0, 76) for x in range(640)]
BG0 = tuple(round(sum(c[i] for c in band) / len(band)) for i in range(3))


def fg_of(kind, sel):
    if kind == 0:
        return (255 - 3 * sel, 255 - sel, 255)
    if kind == 1:
        return (208 + sel + sel // 2, 32 + 2 * sel, 40 + 2 * sel)
    if kind == 2:
        return (0x5C, 0xC4, 0xFF)
    return (0xE0, 0x12, 0x1E)


colours = []
for kind in range(4):
    for sel in range(32):
        f = fg_of(kind, sel)
        for wi in range(8):
            w = wi + 1
            colours.append(tuple((f[i] * w + BG0[i] * (8 - w) + 4) // 8 for i in range(3)))
cv = ['// Generated by sim/generate_subtitle_logo_20261021.py: subtitle colours,',
      '// {kind,sel,opacity-1} -> RGB mixed over the band mean (%d,%d,%d).' % BG0,
      'module subtitle_colour_rom(input wire clk,ce,input wire [9:0] addr,output reg [23:0] q);',
      'reg [23:0] rom[0:1023]; /* fehdl force_ram=1, ram_style="bram" */',
      'initial begin']
cv += ["    rom[%d]=24'h%02X%02X%02X;" % ((i,) + c) for i, c in enumerate(colours)]
cv += ['end', 'always @(posedge clk) if(ce) q<=rom[addr];', 'endmodule', '']
(RTL / 'subtitle_colour_rom.v').write_bytes('\n'.join(cv).encode('utf-8'))
(OUT / 'colour_rom.hex').write_text('\n'.join('%02x%02x%02x' % c for c in colours) + '\n')
print('colour ROM over band mean', BG0)
