"""Generate video_status_font_rom from the music-card title font (20261022).

The A-screen readout (BRI/CON/VOL/RES) uses exactly the glyph rendering of
the song title on the first music card: Noto Sans SC Medium, 24x24 cell,
crisp=True (see generate_dual_lyrics_song6_20261019.font_words).

Latin/digit ink occupies columns 4..18 and rows 5..21 of the 24x24 cell, so
each glyph is stored as 17 rows of 15 two-bit coverage columns (30 bits).
Rows 0..15 live at {code,row}; row 16 lives at 352+code (codes <= 21).

Usage: Python37 generate_status_font24_20261022.py [--write]
"""
from pathlib import Path
import re
import sys
from generate_home_font_patch import rows

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "dual_board/image_link/rtl/resource_round10_20261005/video_status_overlay.v"
# Same code map as video_status_overlay: digits are their value.
CODES = {str(d): d for d in range(10)}
CODES.update({":": 10, "B": 11, "R": 12, "I": 13, "C": 14, "O": 15, "N": 16,
              "V": 17, "L": 18, "E": 19, "S": 20, "x": 21})
COL0, COLS = 4, 15
ROW0, ROWS = 5, 17


def glyph(ch):
    image = rows(ch, 24, 24, crisp=True)
    for y, line in enumerate(image):
        for x, v in enumerate(line):
            inside = ROW0 <= y < ROW0 + ROWS and COL0 <= x < COL0 + COLS
            assert v == 0 or inside, f"{ch!r} ink outside the stored box at {x},{y}"
    return [image[ROW0 + r][COL0:COL0 + COLS] for r in range(ROWS)]


def address(code, row):
    return 352 + code if row == 16 else code * 16 + row


def rom_module():
    lines = [
        "// Music-card title font (Noto Sans SC Medium 24px, crisp), 15x17 ink box,",
        "// two-bit coverage. GENERATED by sim/generate_status_font24_20261022.py.",
        "module video_status_font_rom (",
        "    input  wire        I_clk,",
        "    input  wire [8:0]  I_addr,   // {code,row[3:0]}; row 16 at 352+code",
        "    output reg  [29:0] O_row",
        ");",
        "reg [29:0] rom [0:511];",
        "integer i;",
        "initial begin",
        "    for (i = 0; i < 512; i = i + 1) rom[i] = 30'd0;",
    ]
    for ch, code in sorted(CODES.items(), key=lambda item: item[1]):
        for r, values in enumerate(glyph(ch)):
            word = sum(v << ((COLS - 1 - c) * 2) for c, v in enumerate(values))
            if word:
                lines.append(f"    rom[9'h{address(code, r):03X}] = 30'h{word:08X}; // {ch}")
    lines += ["end", "always @(posedge I_clk) O_row <= rom[I_addr];", "endmodule", ""]
    return "\n".join(lines)


def main():
    module = rom_module()
    source = TARGET.read_text(encoding="utf-8")
    start = source.rindex("\n\n", 0, source.index("module video_status_font_rom")) + 2
    updated = source[:start] + module
    if "--write" in sys.argv:
        TARGET.write_bytes(updated.encode("utf-8"))
        print("wrote", TARGET)
    elif source == updated:
        print("video_status_font_rom matches the music-card font")
    else:
        sys.exit("video_status_font_rom differs; rerun with --write")
    if "--preview" in sys.argv:
        for text in ("BRI:100", "CON:25", "VOL:8", "RES:640x480"):
            cells = [glyph(ch) for ch in text]
            for r in range(ROWS):
                print("".join(" .+#"[v] for cell in cells for v in cell[r] + [0]))
            print()


if __name__ == "__main__":
    main()
