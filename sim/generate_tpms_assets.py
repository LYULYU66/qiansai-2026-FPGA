"""Fixed demonstrator TPMS data; compact native glyphs and top-view car.

Ten 8x12 glyphs share five unused 16x16 home-font entries, no extra font
BRAM. The realistic 32x64 RGBA car is baked to 15 colors + transparency
in one 2048x4 BRAM; no framebuffer, on-chip resize/filter or DSP.
"""
from pathlib import Path
from PIL import Image, ImageFilter
from generate_home_font_patch import rows

ROOT=Path(__file__).resolve().parent.parent
ASSETS=ROOT/'assets/tpms_car_20260930'
CHARS="012456kPa℃"
PAIRS=(14,15,16,18,19)
VALUES=[("10℃","261kPa"),("11℃","264kPa"),
        ("15℃","266kPa"),("10℃","261kPa")]


def packed_car():
    source=Image.open(ASSETS/'source.png').convert('RGBA')
    bounds=source.getchannel('A').point(lambda a:255 if a>=128 else 0).getbbox()
    assert bounds, 'generated car must have nontransparent pixels'
    car=source.crop(bounds)
    car.thumbnail((30,60),Image.Resampling.LANCZOS)
    native=Image.new('RGBA',(32,64),(255,255,255,0))
    native.alpha_composite(car,((32-car.width)//2,(64-car.height)//2))
    white=Image.new('RGBA',native.size,'white')
    white.alpha_composite(native)
    rgb=white.convert('RGB').filter(ImageFilter.UnsharpMask(radius=0.5,percent=135,threshold=5))
    # Reserve one color for the small red tail lamps; unconstrained median-cut
    # otherwise allocates all colors to the much larger silver body/glass.
    quantized=rgb.quantize(colors=14,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    raw=quantized.getpalette()
    colors=[tuple(raw[i*3:i*3+3]) for i in range(14)]+[(181,69,72)]
    pixels=[]
    preview=Image.new('RGB',native.size,'white')
    for y in range(64):
        for x in range(32):
            r,g,b=rgb.getpixel((x,y))
            index=(15 if r-g>18 and r-b>18 else quantized.getpixel((x,y))+1) if native.getpixel((x,y))[3]>=16 else 0
            pixels.append(index)
            if index:preview.putpixel((x,y),colors[index-1])
    return pixels,colors,preview,native


def rom_words():
    words={}
    for pair,slot in enumerate(PAIRS):
        left=rows(CHARS[pair*2],8,12,crisp=True)
        right=rows(CHARS[pair*2+1],8,12,crisp=True)
        for y in range(12):
            values=left[y]+right[y]
            words[slot*16+y]=sum(cov<<(2*(15-x)) for x,cov in enumerate(values))
    return words


def car_module():
    pixels,colors,_,_=packed_car()
    lines=['// Realistic top-view car: 32x64, 4-bit palette index, one BRAM9K.',
           '// Generated by sim/generate_tpms_assets.py; all scaling is offline.',
           'module video_tpms_car_rom (',
           '    input wire I_clk, input wire [10:0] I_addr,',
           '    output reg [3:0] O_index, output reg [23:0] O_rgb',
           ');', 'reg [3:0] car_rom [0:2047];', 'integer i;',
           'initial begin',
           "    for (i=0; i<2048; i=i+1) car_rom[i]=4'd0;"]
    lines += [f"    car_rom[11'd{a}]=4'd{index};" for a,index in enumerate(pixels) if index]
    lines += ['end','always @(posedge I_clk) O_index <= car_rom[I_addr];',
              'always @(*) begin','    case (O_index)']
    for i,(r,g,b) in enumerate(colors,1):
        lines.append(f"        4'd{i}: O_rgb=24'h{r:02X}{g:02X}{b:02X};")
    lines += ["        default: O_rgb=24'hFFFFFF;",'    endcase','end','endmodule']
    return '\n'.join(lines)


if __name__=='__main__':
    _,_,preview,native=packed_car()
    native.save(ASSETS/'car_native32x64.png')
    preview.save(ASSETS/'car_indexed32x64.png')
    preview.save(ASSETS/'car_indexed32x64.ppm')
    preview.resize((256,512),Image.Resampling.NEAREST).save(ASSETS/'car_indexed_zoom.png')
    output=ROOT/'src/user_source/hdl_source/video_home_overlay.v'
    source=output.read_text(encoding='utf-8')
    marker='// Realistic top-view car:'
    if marker in source:
        old=source[source.index(marker):].rstrip()
        new=car_module()
    else:
        old='\n'.join(source.rstrip().splitlines()[-10:])
        new=old+'\n\n'+car_module()
    print('*** Begin Patch\n*** Update File: '+output.relative_to(ROOT).as_posix()+'\n@@')
    print('\n'.join('-'+line for line in old.splitlines()))
    print('\n'.join('+'+line for line in new.splitlines()))
    print('*** End Patch')
