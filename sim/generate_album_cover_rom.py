def main():
    pixels, colors, preview = packed_cover()
    qq_pixels,qq_colors,qq_preview=packed_qq()
    lines = [
        "// Generated by sim/generate_album_cover_rom.py from the user-supplied cover.",
        "// 40px circular cover + 20px QQ logo: 2000/2048 words, one BRAM9K.",
        "module video_album_cover_rom (",
        "    input wire I_clk,",
        "    input wire [10:0] I_addr,",
        "    output reg [3:0] O_index,",
        "    output reg [23:0] O_rgb",
        ");",
        "reg [3:0] rom [0:2047];",
        "integer i;",
        "initial begin",
        "    for (i = 0; i < 2048; i = i + 1) rom[i] = 4'd0;",
    ]
    lines += [f"    rom[11'd{address}] = 4'd{index};"
              for address, index in enumerate(pixels) if index]
    lines += [f"    rom[11'd{1600+address}] = 4'd{index};"
              for address,index in enumerate(qq_pixels) if index]
    lines += [
        "end",
        "reg qq_d;",
        "always @(posedge I_clk) begin",
        "    O_index <= rom[I_addr];",
        "    qq_d <= I_addr >= 11'd1600 && I_addr < 11'd2000;",
        "end",
        "always @(*) begin",
        "    if (qq_d) begin",
        "        case (O_index)",
    ]
    for index,(red,green,blue) in enumerate(qq_colors,1):
        lines.append(f"            4'd{index}: O_rgb = 24'h{red:02X}{green:02X}{blue:02X};")
    lines += ["            default: O_rgb=24'h000000;","        endcase",
              "    end else begin","        case (O_index)"]
    for index, (red, green, blue) in enumerate(colors, 1):
        lines.append(
            f"        4'd{index}: O_rgb = 24'h{red:02X}{green:02X}{blue:02X};"
        )
    lines += [
        "        4'd15: O_rgb = 24'h74CCEE;",
        "        default: O_rgb = 24'h000000;",
        "        endcase",
        "    end",
        "end",
        "endmodule",
    ]
    preview.resize((400, 400), Image.Resampling.NEAREST).save(PREVIEW)
    qq_preview.save(ROOT/"assets/qq_music_20_native.png")
    qq_preview.resize((200,200),Image.Resampling.NEAREST).save(ROOT/"assets/qq_music_20_preview.png")
    old=OUTPUT.read_text(encoding="utf-8").rstrip()
    print("*** Begin Patch\n*** Update File: "+OUTPUT.relative_to(ROOT).as_posix()+"\n@@")
    print("\n".join("-"+l for l in old.splitlines()))
    print("\n".join("+"+l for l in lines))
    print("*** End Patch")


if __name__ == "__main__":
    main()
