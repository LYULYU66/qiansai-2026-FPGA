"""Pack the supplied 40px cover and 20px QQ icon into one 4-bit BRAM ROM.

The circular crop, edge, native sharpening and palettes are baked offline.
HDL is emitted as an apply_patch payload, not written by this generator.
"""
from pathlib import Path
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/jay_chou_cover_source.png"
OUTPUT = ROOT / "src/user_source/hdl_source/video_album_cover_rom.v"
PREVIEW = ROOT / "assets/album_cover_round40_preview.png"
QQ_SOURCE = ROOT / "assets/qq_music_source.png"
SIZE = 40


def packed_cover():
    source = Image.open(SOURCE).convert("RGB")
    side = min(source.size)
    x0 = (source.width - side) // 2
    y0 = (source.height - side) // 2
    reduced = source.crop((x0, y0, x0 + side, y0 + side)).resize(
        (SIZE, SIZE), Image.Resampling.LANCZOS
    )
    reduced = reduced.filter(ImageFilter.UnsharpMask(radius=0.6, percent=160, threshold=6))
    quantized = reduced.quantize(colors=14, method=Image.Quantize.MEDIANCUT)
    palette = quantized.getpalette()
    colors = [tuple(palette[i * 3:i * 3 + 3]) for i in range(14)]
    pixels = []
    preview = Image.new("RGB", (SIZE, SIZE), (19, 37, 55))
    edge = (116, 204, 238)
    for y in range(SIZE):
        for x in range(SIZE):
            distance2 = (x - 19.5) ** 2 + (y - 19.5) ** 2
            if distance2 > 19.5 ** 2:
                index = 0
            elif distance2 >= 18.4 ** 2:
                index = 15
                preview.putpixel((x, y), edge)
            else:
                index = quantized.getpixel((x, y)) + 1
                preview.putpixel((x, y), colors[index - 1])
            pixels.append(index)
    return pixels, colors, preview


