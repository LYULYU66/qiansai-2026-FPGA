"""Emit an apply_patch payload for four sharpened apps, sun and compass.

Four 40x40 app tiles use 15 colors plus transparency, and the sun retains its
32x32 dimensions. A 24px compass occupies spare space. Four 4-bit indices
per word: 2000 used 16-bit words
fit a 2048x16 synchronous ROM (four BRAM9Ks). No runtime resize/decoder/DSP.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter
import sys

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/user_source/hdl_source/video_app_icons_rom.v"
PREVIEW = ROOT / "assets/app_nav_sun_icons_40_preview.png"
SIZE = 40
SUN_SIZE = 32
INPUTS = [
    ("app_navigation_source.png", (102, 32, 241, 173), (245, 246, 248)),
    ("app_music_source.png", (31, 31, 219, 219), (7, 13, 21)),
    ("app_wechat_source.png", (49, 20, 201, 172), (48, 170, 51)),
    ("app_douyin_source.png", (0, 0, 250, 249), (7, 13, 21)),
]

def rounded(x, y, size=SIZE):
    radius = 7
    far_center = size - 1 - radius
    if radius <= x <= far_center or radius <= y <= far_center:
        return True
    cx = radius if x < radius else far_center
    cy = radius if y < radius else far_center
    return (x - cx) ** 2 + (y - cy) ** 2 <= radius ** 2

def logo_tile(filename, box, background, app):
    source = Image.open(ROOT / "assets" / filename).convert("RGB")
    source = source.crop(box).resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    source = source.filter(ImageFilter.UnsharpMask(radius=0.6, percent=160, threshold=6))
    mask = []
    for y in range(SIZE):
        for x in range(SIZE):
            inside = rounded(x, y)
            mask.append(inside)
            if not inside or (app in (1, 3) and
                              (x < 3 or x >= SIZE-3 or y < 3 or y >= SIZE-3)):
                source.putpixel((x, y), background)
    return source, mask

def sun_tile():
    source = Image.open(ROOT / "assets/sun_source.png").convert("RGB")
    source = source.crop((28, 25, 234, 232))
    source = source.resize((SUN_SIZE, SUN_SIZE), Image.Resampling.LANCZOS)
    source = source.filter(ImageFilter.UnsharpMask(radius=0.5, percent=140, threshold=5))
    mask = []
    for y in range(SUN_SIZE):
        for x in range(SUN_SIZE):
            r, g, b = source.getpixel((x, y))
            inside = r > 150 and r > g * 1.02 and g > b * 1.15 and r-b > 35
            mask.append(inside)
            if not inside:
                source.putpixel((x, y), (0, 0, 0))
    return source, mask

def palette_tile(source, mask):
    quantized = source.quantize(colors=15, method=Image.Quantize.MEDIANCUT,
                                dither=Image.Dither.NONE)
    raw = quantized.getpalette()
    palette = [tuple(raw[3*i:3*i+3]) for i in range(15)]
    width, height = source.size
    pixels = [int(quantized.getpixel((i % width, i // width))) + 1 if mask[i]
              else 0 for i in range(width * height)]
    return pixels, palette

def packed_tiles():
    tiles = [logo_tile(name, box, bg, n)
             for n, (name, box, bg) in enumerate(INPUTS)] + [sun_tile(), navigation_disk()]
    return [(source.size[0], *palette_tile(source, mask))
            for source, mask in tiles]


def navigation_disk():
    # Reuse the spare 192 ROM words for a properly antialiased 24px circle
    # and solid white northeast compass arrow. No additional icon BRAM.
    scale=4
    hi=Image.new("RGB",(96,96),(255,255,255))
    mask=Image.new("L",hi.size,0)
    d=ImageDraw.Draw(hi);m=ImageDraw.Draw(mask)
    box=(1,1,94,94)
    d.ellipse(box,fill=(22,139,220));m.ellipse(box,fill=255)
    d.polygon([(8*scale,10*scale),(18*scale,5*scale),
               (13*scale,16*scale),(11*scale,12*scale),
               (7*scale,17*scale),(5.5*scale,15.5*scale),
               (10*scale,11*scale)],fill=(255,255,255))
    native=hi.resize((24,24),Image.Resampling.LANCZOS)
    coverage=mask.resize((24,24),Image.Resampling.LANCZOS)
    return native,[coverage.getpixel((x,y))>=32 for y in range(24) for x in range(24)]

def main():
    packed = packed_tiles()
    words = []
    for size, pixels, _ in packed:
        for base in range(0, size*size, 4):
            words.append(sum(pixels[base+lane] << (12-4*lane) for lane in range(4)))
    assert len(words) == 2000
    preview = Image.new("RGB", (6*52, 52), (255, 255, 255))
    for tile, (size, pixels, palette) in enumerate(packed):
        for y in range(size):
            for x in range(size):
                index = pixels[y*size+x]
                if index:
                    preview.putpixel((tile*52+6+x, y+6), palette[index-1])
    preview.resize((1248, 208), Image.Resampling.NEAREST).save(PREVIEW)
    lines = [
        "// Generated by sim/generate_app_icons_rom.py from supplied icon art.",
        "// Four 40x40 apps, 32x32 sun, 24x24 compass: 2000/2048 words.",
        "// Four BRAM9Ks; all palettes use 15 colors plus transparency.",
        "module video_app_icons_rom (",
        "    input wire I_clk,",
        "    input wire [10:0] I_addr,",
        "    input wire [1:0] I_lane,",
        "    input wire [2:0] I_tile,",
        "    output wire O_opaque,",
        "    output reg [23:0] O_rgb",
        ");",
        'reg [15:0] rom [0:2047]; /* fehdl force_ram=1, ram_style="bram" */',
        "integer i;",
        "initial begin",
        "    for (i=0; i<2048; i=i+1) rom[i]=16'd0;",
    ]
    lines += [f"    rom[11'd{addr}] = 16'h{word:04X};"
              for addr, word in enumerate(words) if word]
    lines += [
        "end",
        "reg [15:0] word_d;",
        "reg [1:0] lane_d;",
        "reg [2:0] tile_d;",
        "always @(posedge I_clk) begin",
        "    word_d <= rom[I_addr];",
        "    lane_d <= I_lane;",
        "    tile_d <= I_tile;",
        "end",
        "reg [3:0] index;",
        "always @(*) begin",
        "    case (lane_d)",
        "        2'd0: index=word_d[15:12];",
        "        2'd1: index=word_d[11:8];",
        "        2'd2: index=word_d[7:4];",
        "        default: index=word_d[3:0];",
        "    endcase",
        "end",
        "assign O_opaque = index != 4'd0;",
        "always @(*) begin",
        "    case ({tile_d,index})",
    ]
    for tile, (_, _, palette) in enumerate(packed):
        for index, (r, g, b) in enumerate(palette, 1):
            lines.append(f"        7'd{tile*16+index}: O_rgb=24'h{r:02X}{g:02X}{b:02X};")
    lines += ["        default: O_rgb=24'h000000;", "    endcase", "end", "endmodule"]
    old = OUT.read_text(encoding="utf-8").rstrip()
    new = "\n".join(lines)
    patch = "*** Begin Patch\n*** Update File: " + OUT.relative_to(ROOT).as_posix()
    patch += "\n@@\n" + "\n".join("-" + line for line in old.splitlines())
    patch += "\n" + "\n".join("+" + line for line in new.splitlines())
    patch += "\n*** End Patch\n"
    sys.stdout.write(patch)

if __name__ == "__main__":
    main()
